/**
 * Settings writes are a patch, so the only thing worth checking beyond `kind` is that a
 * patch arrived at all: an empty object is a no-op, not an error, and the storage layer
 * merges it.
 */
export function isSettingsSet(message: unknown): message is SettingsSetMessage & {
  patch: Record<string, unknown>
} {
  if (!hasKind(message, 'settings:set')) return false
  const patch = (message as { patch?: unknown }).patch
  return typeof patch === 'object' && patch !== null
}

